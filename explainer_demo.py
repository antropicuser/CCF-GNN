"""Generate REAL example explanations from the real CCF graph (deterministic templates).

No model required for this artifact: the importance ranking uses the screened prior
(A = A_CCF weights = aggregated |rho*|), and every printed number (source, target, lag,
rho) comes from the real METR-LA graph. This is exactly the tuple->template path of the
deployed explainer, minus the trained gates.
Outputs: results/example_explanations.json + ../../paper/tables/examples.tex
"""
import json, os
import numpy as np

HERE = os.path.dirname(__file__)
RES = os.path.join(HERE, "results")
TAB = os.path.abspath(os.path.join(HERE, "paper_tables"))

def intensity(rho):
    r = abs(rho)
    if r >= 0.8: return "very strong"
    if r >= 0.6: return "strong"
    if r >= 0.4: return "moderate"
    return "weak"

def main():
    g = np.load(os.path.join(RES, "ccf_graph.npz"))
    mask, rho, tau, val = g["mask"], g["rho_agg"], g["tau_agg"], g["validated"]
    A = np.where(mask, np.abs(rho), 0.0)                     # prior edge weight
    imp = A * np.abs(rho) / (1.0 + tau)                      # Eq. (6) with prior A
    np.fill_diagonal(imp, 0)

    # pick a high-activity target for a readable example
    target = int(np.argmax(val.sum(1)))
    js = np.argsort(-imp[target])[:4]
    js = [j for j in js if mask[target, j] and val[target, j]][:4]

    items = []
    for j in js:
        items.append(dict(source=int(j), target=int(target),
                          lag_min=float(tau[target, j] * 5),
                          rho=round(float(rho[target, j]), 2),
                          intensity=intensity(rho[target, j])))
    multi = (f"The predicted traffic state at sensor {target} is influenced by: " +
             "; ".join(f"({k+1}) {it['intensity']} conditions at upstream sensor {it['source']}, "
                       f"approximately {it['lag_min']:.0f} minutes earlier (rho = {it['rho']:.2f})"
                       for k, it in enumerate(items)) + ".")
    out = dict(target=int(target), edges=items, explanation=multi)
    with open(os.path.join(RES, "example_explanations.json"), "w") as f:
        json.dump(out, f, indent=2)

    tex = "\n".join([
        "% auto-generated by experiments/explainer_demo.py -- REAL graph tuples",
        "\\begin{table}[t]",
        "\\centering\\small",
        "\\caption{A real explanation generated by the deployed template pipeline from the",
        "screened METR-LA graph (top-4 validated in-edges of sensor "
        f"{target} by Eq. (6) on the prior; deterministic rendering)." + "}",
        "\\label{tab:example}",
        "\\begin{tabular}{cccl}",
        "\\toprule",
        "Source & Lag (min) & $\\rho^{*}$ & Intensity band \\\\",
        "\\midrule",
    ])
    for it in items:
        tex += f"{it['source']} & {it['lag_min']:.0f} & {it['rho']:.2f} & {it['intensity']} \\\\\n"
    tex += "\n".join(["\\bottomrule", "\\end{tabular}", "\\end{table}"]) + "\n"
    with open(os.path.join(TAB, "examples.tex"), "w") as f:
        f.write(tex)
    print(json.dumps(out, indent=2))

if __name__ == "__main__":
    main()
