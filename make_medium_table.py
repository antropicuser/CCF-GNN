"""Generate the medium-scale comparison table from results/runs.json (medium run only)."""
import json, os
import numpy as np

RES = os.path.join(os.path.dirname(__file__), "results")
TAB = os.path.abspath(os.path.join(os.path.dirname(__file__), "paper_tables"))

LABEL = {
    "HA":       "Historical Average",
    "full":     "CCF-GNN",
    "windowed": "CCF-GNN (windowed lags, 6 maps)",
    "gwnet":    "Graph WaveNet",
}
ORDER = ["HA", "gwnet", "full", "windowed"]
HORIZONS = ["15min", "30min", "60min"]

def fmt(vals):
    v = np.array(vals, dtype=float)
    if len(v) == 1: return f"{v[0]:.2f}"
    return f"{v.mean():.2f}\\,\\scriptsize$\\pm${v.std(ddof=1):.2f}"

def main():
    runs = json.load(open(os.path.join(RES, "runs.json")))
    lines = [
        "% auto-generated by experiments/make_medium_table.py -- REAL runs, 2 seeds, 25% data",
        "\\begin{table}[t]",
        "\\centering\\small",
        "\\caption{Medium-scale comparison on real METR-LA (25\\% of training windows, width-32,",
        "14 epochs, 2 seeds, CPU; masked MAE in mph; identical budget for both models). This is a",
        "reduced protocol---see Section~\\ref{sec:medium}.}",
        "\\label{tab:medium}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Model & 15\\,min & 30\\,min & 60\\,min & Params \\\\",
        "\\midrule",
    ]
    for mode in ORDER:
        entries = runs.get(mode, [])
        if not entries: continue
        cells = []
        for h in HORIZONS:
            vals = [r[h]["MAE"] for r in entries if h in r]
            cells.append(fmt(vals) if vals else "--")
        params = entries[0].get("_params")
        lines.append(f"{LABEL[mode]} & {cells[0]} & {cells[1]} & {cells[2]} & "
                     f"{(f'{params/1000:.0f}K' if params else '--')} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(os.path.join(TAB, "medium.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.join(TAB, "medium.tex"))

if __name__ == "__main__":
    main()
