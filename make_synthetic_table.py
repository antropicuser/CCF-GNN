"""Generate the synthetic-recovery LaTeX table + figure from aggregated seed runs."""
import json, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(__file__)
RES = os.path.join(HERE, "results")
TAB = os.path.abspath(os.path.join(HERE, "paper_tables"))
FIG = os.path.abspath(os.path.join(HERE, "figures"))

ROWS = [
    ("V1_p_only", "Significance only ($q<0.05$)"),
    ("V2_rho_only", "Effect size only ($|\\rho^{*}|>0.3$)"),
    ("V3_full_admission", "Full admission (V1 $\\wedge$ V2)"),
    ("V4_plus_confound_screen", "V3 $\\wedge$ confounding screen"),
    ("V5_deployed_capK10", "Deployed graph (V4 $\\wedge$ cap $K_g{=}10$)"),
]

def fmt(mu, sd, pct=False):
    s = f"{mu:.3f}" if not pct else f"{mu:.1f}"
    return s if sd == 0 else f"{s}\\,\\scriptsize$\\pm${sd:.3f}" if not pct else f"{s}\\,\\scriptsize$\\pm${sd:.1f}"

def main():
    agg = json.load(open(os.path.join(RES, "synthetic_stats.json")))["aggregated"]
    lines = [
        "% auto-generated by experiments/make_synthetic_table.py -- REAL runs, 3 seeds",
        "\\begin{table}[t]",
        "\\centering\\small",
        "\\caption{Ground-truth recovery on the synthetic traffic benchmark (207 nodes on the real",
        "METR-LA road topology, 725 true time-lagged edges, 5 latent confounders; mean $\\pm$ std",
        "over 3 generator seeds). Each stage of the screening pipeline is ablated.}",
        "\\label{tab:synthetic}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Edge-admission rule & Precision & Recall & F1 & Exact lag (\\%) \\\\",
        "\\midrule",
    ]
    for key, label in ROWS:
        a = agg[key]
        lines.append(
            f"{label} & {fmt(*a['precision'])} & {fmt(*a['recall'])} & {fmt(*a['f1'])} & {fmt(*a['exact_lag_pct'], pct=True)} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(os.path.join(TAB, "synthetic.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")

    # figure: precision/recall bars per variant
    labels = ["V1\np-only", "V2\neffect size", "V3\nfull", "V4\n+CI screen", "V5\ndeployed"]
    x = np.arange(len(labels)); w = 0.38
    P = [agg[k]["precision"][0] for k, _ in ROWS]; Pe = [agg[k]["precision"][1] for k, _ in ROWS]
    R = [agg[k]["recall"][0] for k, _ in ROWS]; Re = [agg[k]["recall"][1] for k, _ in ROWS]
    fig, ax = plt.subplots(figsize=(6.2, 2.9))
    ax.bar(x - w/2, P, w, yerr=Pe, capsize=3, label="Precision", color="#4878CF", edgecolor="white")
    ax.bar(x + w/2, R, w, yerr=Re, capsize=3, label="Recall", color="#EE854A", edgecolor="white")
    ax.set_xticks(x); ax.set_xticklabels(labels, fontsize=8)
    ax.set_ylim(0, 1.05); ax.set_ylabel("score")
    ax.legend(fontsize=8, loc="center right")
    plt.tight_layout()
    plt.savefig(os.path.join(FIG, "synthetic_pr.pdf"), bbox_inches="tight")
    print("wrote table + figure")

if __name__ == "__main__":
    main()
