"""Real robustness evaluation: random node masking at test time.

Loads the saved medium-scale checkpoints (ckpt_full_s2.pt, ckpt_gwnet_s2.pt), masks the
INPUTS of a random subset of nodes (0/5/10/15%), and evaluates masked MAE on the remaining
(unmasked) nodes on the real METR-LA test split (25% windows, same as training protocol).
Each level is repeated over 5 independent mask draws; reports mean +/- std of the relative
MAE increase over the 0% baseline.

Outputs: results/robustness.json, ../../paper/tables/robustness.tex
"""
import json, os, sys
import numpy as np
import torch

sys.path.insert(0, os.path.dirname(__file__))
from data_utils import load_split, zscore_fit, load_graph, masked_metrics
from models.ccf_gnn import CCF_GNN
from models.gwnet import GWNet

HERE = os.path.dirname(__file__)
RES = os.path.join(HERE, "results")
TAB = os.path.abspath(os.path.join(HERE, "paper_tables"))
LEVELS = [0, 5, 10, 15]
DRAWS = 5
BATCH = 64

def predict(model, X, Y, mu, sd, rng, mask_frac):
    """Mask `mask_frac`% of nodes' inputs (per draw, same nodes for the whole pass)."""
    N = X.shape[1]
    k = int(round(N * mask_frac / 100.0))
    masked_nodes = rng.choice(N, size=k, replace=False) if k > 0 else np.array([], dtype=int)
    keep = np.setdiff1d(np.arange(N), masked_nodes)
    Xc = X.copy()
    Xc[:, masked_nodes, :] = 0.0
    preds = np.zeros_like(Y, dtype=np.float32)
    with torch.no_grad():
        for s in range(0, len(Xc), BATCH):
            xb = torch.tensor((Xc[s:s+BATCH] - mu) / sd, dtype=torch.float32).transpose(1, 2)
            preds[s:s+BATCH] = model(xb).numpy() * sd + mu
    return preds, keep

def eval_model(model, X, Y, mu, sd):
    out = {}
    for frac in LEVELS:
        maes = []
        for d in range(DRAWS):
            rng = np.random.default_rng(100 + d)
            preds, keep = predict(model, X, Y, mu, sd, rng, frac)
            r = masked_metrics(preds[:, keep, :], Y[:, keep, :])
            maes.append(r["MAE"])
        out[f"{frac}%"] = [round(float(np.mean(maes)), 3), round(float(np.std(maes)), 3)]
    base = out["0%"][0]
    for frac in LEVELS[1:]:
        m, s = out[f"{frac}%"]
        out[f"{frac}%_rel"] = [round(100 * (m - base) / base, 1), round(100 * s / base, 1)]
    return out

def main():
    Xte, Yte, _ = load_split("test", stride=4)
    Xtr, _, _ = load_split("train", stride=4)
    mu, sd = zscore_fit(Xtr)
    del Xtr
    g = load_graph(k_cap=10)

    results = {}
    for name, cls in [("ccf_gnn", lambda: CCF_GNN(g, d=32)),
                      ("gwnet",   lambda: GWNet(Xte.shape[1], d=32))]:
        ck = os.path.join(RES, f"ckpt_{'full' if name=='ccf_gnn' else 'gwnet'}_s2.pt")
        if not os.path.exists(ck):
            print("missing checkpoint:", ck); continue
        model = cls()
        model.load_state_dict(torch.load(ck, map_location="cpu"))
        model.eval()
        results[name] = eval_model(model, Xte, Yte, mu, sd)
        print(name, json.dumps(results[name]), flush=True)

    with open(os.path.join(RES, "robustness.json"), "w") as f:
        json.dump(dict(levels=LEVELS, draws=DRAWS, results=results), f, indent=2)

    # LaTeX table (real numbers)
    if "ccf_gnn" in results and "gwnet" in results:
        rows = [
            ("CCF-GNN", "ccf_gnn"),
            ("Graph WaveNet", "gwnet"),
        ]
        lines = [
            "% auto-generated by experiments/robustness_eval.py -- REAL runs",
            "\\begin{table}[t]",
            "\\centering\\small",
            "\\caption{Robustness to random sensor masking on real METR-LA (test split; inputs of",
            "$k\\%$ of nodes zeroed, MAE evaluated on the remaining nodes; medium-scale checkpoints,",
            "5 mask draws, mean $\\pm$ std of the relative MAE increase over the unmasked baseline).}",
            "\\label{tab:robust}",
            "\\begin{tabular}{lccc}",
            "\\toprule",
            "Model & 5\\% masked & 10\\% masked & 15\\% masked \\\\",
            "\\midrule",
        ]
        for label, key in rows:
            cells = [f"{results[key][f'{lv}%_rel'][0]:.1f}\\,\\scriptsize$\\pm${results[key][f'{lv}%_rel'][1]:.1f}\\%"
                     for lv in LEVELS[1:]]
            lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
        with open(os.path.join(TAB, "robustness.tex"), "w") as f:
            f.write("\n".join(lines) + "\n")
        print("wrote robustness table")

if __name__ == "__main__":
    main()
