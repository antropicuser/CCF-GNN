"""Generate LaTeX table fragments from results/runs.json (real runs only).

Usage:  python make_tables.py
Writes: ../paper/tables/pilot.tex
If runs.json is missing/empty, writes a clearly-marked placeholder table.
"""
import json, os
import numpy as np

RES = os.path.join(os.path.dirname(__file__), "results")
TAB = os.path.join(os.path.dirname(__file__), "paper_tables")
os.makedirs(TAB, exist_ok=True)

LABEL = {
    "full":     "CCF-GNN (pilot)",
    "gwnet":    "Graph WaveNet (pilot, same budget)",
    "nolag":    "\\quad w/o time-aligned lags ($\\tau^{*}{=}1$)",
    "nohybrid": "\\quad w/o hybrid gate ($\\alpha\\equiv 1$, fixed CCF prior)",
    "HA":       "Historical Average",
}
ORDER = ["HA", "gwnet", "full", "nolag", "nohybrid"]
HORIZONS = ["15min", "30min", "60min"]

def mean_std(vals):
    v = np.array(vals, dtype=float)
    if len(v) == 1: return f"{v[0]:.2f}", None
    return f"{v.mean():.2f}", f"{v.std(ddof=1):.2f}"

def main():
    path = os.path.join(RES, "runs.json")
    runs = json.load(open(path)) if os.path.exists(path) else {}
    lines = [
        "% auto-generated by experiments/make_tables.py -- DO NOT EDIT BY HAND",
        "\\begin{table}[t]",
        "\\centering\\small",
        "\\caption{Reduced-scale pilot on METR-LA (real outputs of the released code: window"
        " subsampling, width-32, 6 epochs, 2 CPU cores, 2 seeds). Not comparable to the full"
        " protocol; see Section~\\ref{sec:pilot}. Masked MAE (mph).}",
        "\\label{tab:pilot}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Configuration & 15\\,min & 30\\,min & 60\\,min \\\\",
        "\\midrule",
    ]
    filled = False
    for mode in ORDER:
        if mode not in runs or not runs[mode]: continue
        filled = True
        cells = []
        for h in HORIZONS:
            vals = [r[h]["MAE"] for r in runs[mode] if h in r]
            if not vals: cells.append("--"); continue
            m, s = mean_std(vals)
            cells.append(m if s is None else f"{m}\\,\\scriptsize$\\pm${s}")
        lines.append(f"{LABEL[mode]} & {cells[0]} & {cells[1]} & {cells[2]} \\\\")
    if not filled:
        lines.append("\\emph{[placeholder -- run experiments/run\\_pilot.sh]} & -- & -- & -- \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(os.path.join(TAB, "pilot.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.join(TAB, "pilot.tex"), "(filled)" if filled else "(placeholder)")

if __name__ == "__main__":
    main()
