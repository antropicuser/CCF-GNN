"""Real audit: relationship between road distance and estimated lag, split by screen verdict.

Uses the official sensor-id mapping + road distances (distances.csv, metres) and the REAL
CCF graph (results/ccf_graph.npz). Reports per verdict group (validated / confounded):
mean road distance, and Spearman correlation between road distance and optimal lag.
Outputs: results/distance_lag_audit.json (+ LaTeX fragment tables/distance_audit.tex)
"""
import json, os
import numpy as np
import pandas as pd
from scipy.sparse import csr_matrix
from scipy.sparse.csgraph import dijkstra
from scipy.stats import spearmanr

HERE = os.path.dirname(__file__)
RES = os.path.join(HERE, "results")
TAB = os.path.abspath(os.path.join(HERE, "paper_tables"))

def main():
    mapping = json.load(open(os.path.join(HERE, "data", "adj_mx_mapping.json")))
    # mapping: {"sensor_ids": [...], "sensor_to_ind": {id: idx}} (official DCRNN format)
    ids = mapping["sensor_ids"] if isinstance(mapping, dict) else []
    N = len(ids) if ids else 207
    dist = pd.read_csv(os.path.join(HERE, "data", "distances.csv"))
    rows, cols, vals = [], [], []
    id2idx = {int(sid): i for i, sid in enumerate(ids)}
    if not id2idx:
        print("mapping format unexpected; aborting"); return
    for a, b, c in dist.itertuples(index=False):
        ia, ib = id2idx.get(int(a)), id2idx.get(int(b))
        if ia is None or ib is None: continue
        rows.append(ia); cols.append(ib); vals.append(float(c))
    W = csr_matrix((vals, (rows, cols)), shape=(N, N))
    D = dijkstra(W, directed=True)
    g = np.load(os.path.join(RES, "ccf_graph.npz"))
    mask, val, conf, tau = g["mask"], g["validated"], g["confounded"], g["tau_agg"]
    out = {}
    for name, sel in [("validated", val & mask), ("confounded", conf & mask)]:
        ii, jj = np.nonzero(sel)              # i target, j source
        d_km, lag_min = [], []
        for i, j in zip(ii, jj):
            dd = D[j, i]
            if np.isfinite(dd):
                d_km.append(dd / 1000.0); lag_min.append(tau[i, j] * 5)
        d_km = np.array(d_km); lag_min = np.array(lag_min)
        rho, p = spearmanr(d_km, lag_min)
        out[name] = dict(n=int(len(d_km)), mean_dist_km=round(float(d_km.mean()), 2),
                         median_dist_km=round(float(np.median(d_km)), 2),
                         spearman_rho=round(float(rho), 3), p_value=float(p))
        print(name, out[name], flush=True)
    with open(os.path.join(RES, "distance_lag_audit.json"), "w") as f:
        json.dump(out, f, indent=2)

    if "validated" in out and "confounded" in out:
        v, c = out["validated"], out["confounded"]
        tex = "\n".join([
            "% auto-generated by experiments/audit_distance_lag.py -- REAL data",
            "\\begin{table}[t]",
            "\\centering\\small",
            "\\caption{Road distance vs.\\ estimated propagation lag for REAL CCF edges (METR-LA),",
            "split by the confounding-screen verdict. Distances are shortest-path road distances",
            "(metres, official release); lags are the aggregated optimal lags.}",
            "\\label{tab:distance_audit}",
            "\\begin{tabular}{lcccc}",
            "\\toprule",
            "Edge group & $n$ & Mean dist.\\ (km) & Median dist.\\ (km) & Spearman $\\rho$ (dist., lag) \\\\",
            "\\midrule",
            f"Screen-validated & {v['n']:,} & {v['mean_dist_km']:.2f} & {v['median_dist_km']:.2f} & "
            f"{v['spearman_rho']:.3f} ($p{{=}}{v['p_value']:.1e}$) \\\\",
            f"Screen-flagged (confounded) & {c['n']:,} & {c['mean_dist_km']:.2f} & {c['median_dist_km']:.2f} & "
            f"{c['spearman_rho']:.3f} ($p{{=}}{c['p_value']:.1e}$) \\\\",
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}",
        ]) + "\n"
        with open(os.path.join(TAB, "distance_audit.tex"), "w") as f:
            f.write(tex)
        print("wrote distance audit table")

if __name__ == "__main__":
    main()
